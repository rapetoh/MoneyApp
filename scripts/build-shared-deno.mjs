#!/usr/bin/env node
/**
 * Generates the Deno-importable build of `@voice-expense/shared` that the
 * Edge Functions import.
 *
 * Why this exists. Edge Functions run on Deno, which resolves only
 * explicit, extensioned specifiers, while `packages/shared` is ordinary
 * Node-style TypeScript (`from './recurrence'`, `from '../i18n'`, JSON
 * locale imports). Deno cannot read that package directly, and the
 * Supabase CLI deploys a function's own directory tree. Before this
 * script, the answer was to hand-port the needed functions into
 * `supabase/functions/_shared/` under a "DO NOT HAND-EDIT THE LOGIC"
 * header and remember to port every future change by hand
 * (`_shared/recurrence.ts`, fix-plan 1.5). That is a copy that silently
 * rots: the day it drifts, the server and the apps disagree about a
 * user's money and nothing fails loudly.
 *
 * So the copy is *generated* instead. One bundle, one source of truth,
 * regenerated by `npm run build:shared-deno` and verified in CI by
 * `--check` (which fails when the committed bundle no longer matches the
 * sources). The bundle is committed because `supabase functions deploy`
 * ships the directory as it stands on disk.
 *
 * The output is a single self-contained ESM file with no imports: the
 * shared package has zero runtime dependencies (its only `@supabase/*`
 * references are `import type`, erased at build), and the i18n JSON
 * locales are inlined.
 */
import { build } from 'esbuild'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const ENTRY = path.join(root, 'packages/shared/src/index.ts')
const OUT = path.join(root, 'supabase/functions/_shared/generated/shared.ts')

const BANNER = `// GENERATED FILE - DO NOT EDIT.
//
// Source:    packages/shared/src/index.ts (the real @voice-expense/shared)
// Generator: scripts/build-shared-deno.mjs
// Regenerate: npm run build:shared-deno
//
// Edge Functions import this instead of hand-ported copies, so the server
// runs byte-identical domain logic to the iOS and web apps. Editing this
// file by hand is always wrong: the next regeneration silently discards
// the edit. Change packages/shared and regenerate.
//
// deno-lint-ignore-file
// @ts-nocheck
`

async function generate() {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    format: 'esm',
    // `neutral` keeps Node and browser globals out of the output: this has
    // to run on Deno, where neither is guaranteed.
    platform: 'neutral',
    target: 'es2022',
    // Readability matters here - this file gets read when a notification
    // says something wrong and someone needs to see which branch produced it.
    minify: false,
    write: false,
    loader: { '.json': 'json' },
    logLevel: 'silent',
  })

  if (result.outputFiles.length !== 1) {
    throw new Error(`expected one output file, got ${result.outputFiles.length}`)
  }
  const code = result.outputFiles[0].text

  // A stray `import`/`require` would fail at deploy time rather than here,
  // where the message can say what to do about it.
  const leftover = code.match(/^\s*import\s.+from\s+['"](.+)['"]/m)
  if (leftover) {
    throw new Error(
      `bundle still imports "${leftover[1]}" - the shared package gained a runtime dependency.\n` +
        `Edge Functions cannot resolve it. Either drop the dependency or mark it external and vendor it deliberately.`,
    )
  }
  return BANNER + code
}

const checkOnly = process.argv.includes('--check')
const next = await generate()

if (checkOnly) {
  const current = existsSync(OUT) ? await readFile(OUT, 'utf8') : null
  if (current !== next) {
    console.error(
      `\n  supabase/functions/_shared/generated/shared.ts is stale.\n` +
        `  packages/shared changed without regenerating the Edge Function bundle,\n` +
        `  so the server would run different logic to the apps.\n\n` +
        `  Fix:  npm run build:shared-deno\n`,
    )
    process.exit(1)
  }
  console.log('shared-deno bundle is up to date')
} else {
  await mkdir(path.dirname(OUT), { recursive: true })
  await writeFile(OUT, next)
  console.log(`wrote ${path.relative(root, OUT)} (${(next.length / 1024).toFixed(1)} kB)`)
}
